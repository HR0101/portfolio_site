/**
 * Fine coastline mask for the Hero globe, separate from the loader's dot map.
 * Input: world-atlas@2.0.2/land-50m.json (ISC), Natural Earth (public domain).
 * curl -fL https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-50m.json -o /tmp/land-50m.json
 * node scripts/generate-planet-land.mjs /tmp/land-50m.json > src/lib/planetLandMask.ts
 */
import { readFileSync } from 'node:fs';

const COLUMNS = 480, ROWS = 192, TOP = 84, BOTTOM = -60;
const topology = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const [sx, sy] = topology.transform.scale;
const [tx, ty] = topology.transform.translate;
const arcs = topology.arcs.map(arc => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * sx + tx, y * sy + ty]; });
});
function ring(indexes) {
  const points = [];
  for (const index of indexes) {
    const arc = index < 0 ? [...arcs[~index]].reverse() : arcs[index];
    points.push(...(points.length ? arc.slice(1) : arc));
  }
  let previous = points[0][0];
  return points.map(([x, y]) => {
    while (x - previous > 180) x -= 360;
    while (x - previous < -180) x += 360;
    previous = x;
    return [x, y];
  });
}
const bits = new Uint8Array(COLUMNS * ROWS);
const step = 360 / COLUMNS;
for (const geometry of topology.objects.land.geometries) {
  const polygons = geometry.type === 'MultiPolygon' ? geometry.arcs : [geometry.arcs];
  for (const polygon of polygons) {
    const rings = polygon.map(ring);
    const latitudes = rings.flat().map(point => point[1]);
    const north = Math.max(...latitudes), south = Math.min(...latitudes);
    if (north < BOTTOM || south > TOP) continue;
    for (let row = 0; row < ROWS; row++) {
      const latitude = TOP - (row + .5) * step;
      if (latitude < south || latitude > north) continue;
      const intersections = [];
      for (const points of rings) {
        for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
          const [x1, y1] = points[j], [x2, y2] = points[i];
          if ((y1 > latitude) !== (y2 > latitude)) intersections.push(x1 + (latitude - y1) / (y2 - y1) * (x2 - x1));
        }
      }
      intersections.sort((a, b) => a - b);
      for (let i = 0; i + 1 < intersections.length; i += 2) {
        for (const shift of [-360, 0, 360]) {
          const start = Math.max(0, Math.ceil((intersections[i] + shift + 180) / step - .5));
          const end = Math.min(COLUMNS - 1, Math.floor((intersections[i + 1] + shift + 180) / step - .5));
          if (end >= start) bits.fill(1, row * COLUMNS + start, row * COLUMNS + end + 1);
        }
      }
    }
  }
}
const packed = new Uint8Array(Math.ceil(bits.length / 8));
bits.forEach((value, index) => { packed[index >> 3] |= value << (7 - (index & 7)); });
console.error(`Coastline mask: ${bits.reduce((sum, value) => sum + value, 0)} land cells / ${bits.length}`);
console.log(`// Generated by scripts/generate-planet-land.mjs. Do not edit by hand.
// Natural Earth 1:50m land (public domain), via world-atlas@2.0.2 (ISC).
export const PLANET_LAND_COLUMNS = ${COLUMNS};
export const PLANET_LAND_ROWS = ${ROWS};
export const PLANET_LAND_TOP = ${TOP};
export const PLANET_LAND_BOTTOM = ${BOTTOM};
export const PLANET_LAND_BITS = '${Buffer.from(packed).toString('base64')}';
`);
